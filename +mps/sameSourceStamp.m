function tf = sameSourceStamp(a, b)
%SAMESOURCESTAMP True when two mps.sourceStamp records describe one state.

    tf = false;
    if ~isstruct(a) || ~isstruct(b) || ...
            ~isfield(a, 'datenum') || ~isfield(b, 'datenum')
        return;
    end
    if ~isfield(a, 'checksum') || ~isfield(b, 'checksum') || ...
            ~isfield(a, 'weightedChecksum') || ...
            ~isfield(b, 'weightedChecksum')
        return;
    end
    tf = abs(double(a.datenum) - double(b.datenum)) < 1e-8 && ...
        double(a.bytes) == double(b.bytes) && ...
        double(a.chars) == double(b.chars) && ...
        double(a.checksum) == double(b.checksum) && ...
        double(a.weightedChecksum) == double(b.weightedChecksum);
end
