    h.XDrop = uidropdown(pg, 'Items', {noneLabel}, 'Value', noneLabel);
    h.XDrop.Layout.Row = 1;
    h.XDrop.Layout.Column = [2 3];

    uilabel(pg, 'Text', mps.tr('Y 轴（可多选）', 'Y axis (multi-select)'));
