        'Text', mps.tr('入口...', 'Entry point'), ...
        'Enable', 'off', ...
        'ButtonPushedFcn', @(s, e) cb.onChooseEntry());
    h.EntryButton.Layout.Column = 8;

    if isEnglish
        tableWidths = {40, 46, 60, 110, 66, 66, 44, 76, 150, '1x'};
    else
        tableWidths = {40, 46, 90, 150, 66, 66, 30, 64, 100, '1x'};
    end
