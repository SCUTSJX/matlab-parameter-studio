function ws = summarizeWhos(vars)
%SUMMARIZEWHOS Lightweight workspace summary from whos metadata.
%
%   Used for lazy workspaces where loading every variable just to compute
%   min/max/preview would defeat the memory optimization.

    ws = struct('name', {}, 'class', {}, 'size', {}, ...
        'min', {}, 'max', {}, 'preview', {});
    for k = 1:numel(vars)
        sz = vars(k).size;
        szStr = sprintf('%dx', sz);
        szStr = szStr(1:end-1);
        ws(end+1) = struct( ...
            'name', vars(k).name, ...
            'class', vars(k).class, ...
            'size', szStr, ...
            'min', [], ...
            'max', [], ...
            'preview', sprintf('%s %s', szStr, vars(k).class)); %#ok<AGROW>
    end
end
