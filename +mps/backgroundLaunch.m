function future = backgroundLaunch(app, pool)
%BACKGROUNDLAUNCH Submit the app's single/background project run.
%
%   Kept outside App so the background lifecycle can live in
%   mps.BackgroundRunManager without exposing App internals.

    if app.ProjectMode || ...
            (~isempty(app.EntryFile) && ...
            ~strcmpi(app.EntryFile, app.SourceFile))
        future = parfeval(pool, @mps.backgroundProjectRun, 1, ...
            app.SourceFile, app.EntryFile, app.Params, ...
            app.MaxVariableMB, app.MaxTotalMB, app.SaveFigFiles, ...
            app.FigureResolution, app.LazyWorkspaceMB);
    else
        future = parfeval(pool, @mps.backgroundRun, 1, ...
            app.SourceFile, app.Params, app.MaxVariableMB, ...
            app.MaxTotalMB, app.SaveFigFiles, app.FigureResolution, ...
            app.LazyWorkspaceMB);
    end
end
