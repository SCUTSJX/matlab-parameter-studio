function showQuickStart()
%SHOWQUICKSTART One-screen, plain-language quick start.

    fig = uifigure('Name', mps.tr('快速上手', 'Quick start'), ...
        'Position', [320 180 640 480]);
    g = uigridlayout(fig, [2 1]);
    g.RowHeight = {'1x', 34};
    g.Padding = [14 14 14 14];
    g.RowSpacing = 10;
    txt = { ...
        mps.tr('30 秒上手', 'Quick start in 30 seconds'), ...
        '', ...
        mps.tr('1. 点“打开 .m 文件”，选一个 MATLAB 脚本。', ...
            '1. Click "Open .m file" and choose a MATLAB script.'), ...
        mps.tr('2. 左侧表格列出能改的参数：在“新值”列输入新的数字。', ...
            '2. The table on the left lists tunable parameters: enter new numbers in the "New value" column.'), ...
        mps.tr('    “使用”打勾 = 本次运行用这个新值；', ...
            '    Check "Use" = this run uses the new value;'), ...
        mps.tr('    “锁定”打勾 = 这个参数不许改，永远保持原值。', ...
            '    Check "Lock" = this parameter cannot change and always keeps its original value.'), ...
        mps.tr('3. 点“运行”（快捷键 F5）。', ...
            '3. Click "Run" (or press F5).'), ...
        mps.tr('4. 看结果：', '4. Review the results:'), ...
        mps.tr('    · “结果图”看脚本产生的图；', ...
            '    · "Results" shows the figures produced by the script;'), ...
        mps.tr('    · “工作区”看变量；“绘图”里可自己选 X/Y 出图、导出 CSV；', ...
            '    · "Workspace" shows variables; use "Plot" to choose X/Y and export CSV;'), ...
        mps.tr('    · “打开报告”看 HTML 报告（参数变化 + 图 + 变量 + 日志）。', ...
            '    · "Open report" shows the HTML report (parameter changes + figures + variables + log).'), ...
        mps.tr('5. 满意后点“保存调参 .m”，得到可以直接运行的脚本。', ...
            '5. When happy, click "Save tuned .m" to get a script you can run directly.'), ...
        '', ...
        mps.tr('常用进阶（不清楚可以先不用）：', ...
            'Useful next steps (skip them if unsure):'), ...
        mps.tr('· 批量改参数：Ctrl/Shift 多选行 → 点“批量修改...”或按 Ctrl+B。', ...
            '· Bulk edit parameters: Ctrl/Shift-select rows → click "Bulk edit..." or press Ctrl+B.'), ...
        mps.tr('· 改错了：Ctrl+Z 撤销，Ctrl+Y 重做（表格下方也有按钮）。', ...
            '· Made a mistake: Ctrl+Z to undo, Ctrl+Y to redo (buttons below the table too).'), ...
        mps.tr('· 双击参数行：在 MATLAB 编辑器中打开对应源码位置。', ...
            '· Double-click a parameter row: open that source line in the MATLAB editor.'), ...
        mps.tr('· 配置函数（如 p156_catalog.m）不能直接跑：点“入口...”选择 run_xxx.m。', ...
            '· Config functions (e.g. p156_catalog.m) cannot run directly: click "Entry point..." and choose run_xxx.m.'), ...
        mps.tr('· 关闭应用后重新打开同一脚本，会恢复上次未运行的修改。', ...
            '· Reopening the same script after closing the app restores unrun edits from last time.'), ...
        mps.tr('· 保存调参 .m 前会先显示 diff，确认后才写文件。', ...
            '· Saving a tuned .m shows the diff first and writes the file only after you confirm.'), ...
        mps.tr('· 看不懂参数含义：生成注释 JSON → 给 AI 填写 → 导入注释。', ...
            '· Not sure what a parameter means: Generate annotation JSON → have an AI fill it in → Import annotations.'), ...
        mps.tr('· 想存几套方案：在“参数集”输入名字 → 保存为参数集。', ...
            '· Want several setups: enter a name in the preset field → Save as preset.'), ...
        mps.tr('· 想对比两次：点“运行历史”，任选两次设为 A/B 后对比。', ...
            '· Compare two runs: click "Run history", set any two runs as A/B, then compare.'), ...
        mps.tr('· 想批量试值：点“批量扫描...”，填 1,2,4 或 1:0.5:5。', ...
            '· Try many values: click "Batch sweep...", enter 1,2,4 or 1:0.5:5.'), ...
        '', ...
        mps.tr('提示：运行脚本时图窗默认不弹出，不会打扰你；', ...
            'Tip: figures do not pop up during runs by default, so they will not interrupt you;'), ...
        mps.tr('想看就勾“保留结果图窗”。', ...
            'check "Keep figures" to see them.')};
    ta = uitextarea(g, 'Editable', 'off', 'FontSize', 12, 'Value', txt);
    ta.Layout.Row = 1;
    b = uibutton(g, 'Text', mps.tr('知道了', 'Got it'), ...
        'ButtonPushedFcn', @(s, e) delete(fig));
    b.Layout.Row = 2;
    uiwait(fig);
end
